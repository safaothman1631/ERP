# ─────────────────────────────────────────────────────────────────────────────
# Property 7: Backup archive round-trip preserves document set
# ─────────────────────────────────────────────────────────────────────────────

# Feature: system-health-backup, Property 7
@given(
    collections=st.dictionaries(
        keys=st.sampled_from(BackupService.COLLECTIONS),
        values=st.lists(
            st.fixed_dictionaries({"id": st.uuids().map(str)}),
            max_size=20,
        ),
        min_size=1,
    )
)
@h_settings(max_examples=100)
def test_property7_backup_round_trip_preserves_document_set(collections):
    """
    **Validates: Requirements 5.6**

    # Feature: system-health-backup, Property 7: Backup archive round-trip preserves document set

    Serialize → compress → decompress → parse must yield the same collection
    names, same document counts per collection, and same document IDs.
    """
    svc = _make_service()

    archive_payload = {
        "org_id": "test-org",
        "exported_at": "2024-01-15T02:00:00+00:00",
        "version": "1.0",
        "collections": collections,
    }

    # Serialize → compress
    raw_bytes = svc._serialize_to_json(archive_payload)
    compressed = svc._compress(raw_bytes)

    # Decompress → parse
    decompressed = gzip.decompress(compressed)
    parsed = json.loads(decompressed)

    parsed_collections = parsed["collections"]

    # Same collection names present
    assert set(parsed_collections.keys()) == set(collections.keys()), (
        f"Collection names differ after round-trip: "
        f"expected {set(collections.keys())}, got {set(parsed_collections.keys())}"
    )

    for col_name, original_docs in collections.items():
        parsed_docs = parsed_collections[col_name]

        # Same document count per collection
        assert len(parsed_docs) == len(original_docs), (
            f"Document count mismatch in collection '{col_name}': "
            f"expected {len(original_docs)}, got {len(parsed_docs)}"
        )

        # Same document IDs (order-preserving)
        original_ids = [doc["id"] for doc in original_docs]
        parsed_ids = [doc["id"] for doc in parsed_docs]
        assert parsed_ids == original_ids, (
            f"Document IDs differ in collection '{col_name}': "
            f"expected {original_ids}, got {parsed_ids}"
        )


