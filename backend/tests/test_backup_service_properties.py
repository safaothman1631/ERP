@h_settings(max_examples=100)
def test_property9_integrity_count_match_yields_verified(collections):
    """
    **Validates: Requirements 5.3, 5.4**

    # Feature: system-health-backup, Property 9: Integrity verification correctly classifies count match/mismatch

    When the exported document count equals the count obtained by decompressing
    and re-counting the archive, integrity_status SHALL be "verified".
    When the counts differ, integrity_status SHALL be "failed".

    This tests the pure counting logic without Cloud Storage I/O.
    """
    svc = _make_service()

    # Build archive with known document count
    archive_payload = {
        "org_id": "test-org",
        "exported_at": "2024-01-15T02:00:00+00:00",
        "version": "1.0",
        "collections": collections,
    }
    exported_count = sum(len(docs) for docs in collections.values())

    # Serialize and compress
    raw_bytes = svc._serialize_to_json(archive_payload)
    compressed = svc._compress(raw_bytes)

    # Simulate the integrity check: decompress and count
    decompressed = gzip.decompress(compressed)
    parsed = json.loads(decompressed)
    verified_count = sum(len(docs) for docs in parsed["collections"].values())

    # Counts must match → integrity_status would be "verified"
    assert verified_count == exported_count, (
        f"Count mismatch after round-trip: exported={exported_count}, "
        f"verified={verified_count}"
    )

    # Simulate the classification logic from _do_verify:
    # (actual_count == expected_count) → True → "verified"
    integrity_passes = (verified_count == exported_count)
    assert integrity_passes is True, (
        f"Integrity check should pass when counts match "
        f"(exported={exported_count}, verified={verified_count})"
    )


