"""
Property-Based Tests for BackupService utility methods (Properties 7, 8, 9, 10, 12, 13).

**Validates: Requirements 5.2, 5.3, 5.4, 5.6, 4.5, 4.8, 10.6**

Property 7: Backup archive round-trip preserves document set
    For any valid backup archive (a dict mapping collection names to lists of
    documents), serializing to JSON, gzip-compressing, decompressing, and
    JSON-parsing SHALL produce a document set equivalent to the original
    (same collection names, same document count per collection, same document IDs).

Property 8: SHA-256 checksum is deterministic
    For any byte sequence b, calling _compute_checksum(b) twice SHALL return
    the same hex string both times.

Property 12: Empty collections are included in backup
    For any subset of the 40 required collections that have zero documents,
    the backup archive SHALL still include those collections as empty arrays,
    and the total document count SHALL be 0 (satisfying integrity_status == "verified"
    when exported count == verified count == 0).

Property 9: Integrity verification correctly classifies count match/mismatch
    For any backup archive where the exported document count equals the count
    obtained by decompressing and counting the uploaded file, integrity_status
    SHALL be "verified". For any archive where the counts differ, integrity_status
    SHALL be "failed".

Property 10: Backup record contains all required fields
    For any completed backup run (success or failure), the resulting BackupRecord
    SHALL contain non-null values for all 11 required fields: id, org_id, filename,
    storage_path, created_at, status, integrity_status, total_documents,
    collections_backed_up, file_size_bytes, and checksum_sha256.

Property 13: Org-scoped storage paths
    For any org_id, every storage_path generated by BackupService SHALL start
    with f"backups/{org_id}/".
"""

