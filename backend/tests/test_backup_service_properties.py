# ─────────────────────────────────────────────────────────────────────────────

# Feature: system-health-backup, Property 8
@given(data=st.binary())
@h_settings(max_examples=100)
def test_property8_checksum_is_deterministic(data):
    """
    **Validates: Requirements 5.2**

    # Feature: system-health-backup, Property 8: SHA-256 checksum is deterministic

    Calling _compute_checksum(b) twice on the same byte sequence SHALL return
    the identical hex string both times.
    """
    svc = _make_service()

    first = svc._compute_checksum(data)
    second = svc._compute_checksum(data)

    assert first == second, (
        f"_compute_checksum returned different values for the same input: "
        f"{first!r} vs {second!r}"
    )

    # Also verify the result looks like a valid SHA-256 hex digest (64 hex chars)
    assert len(first) == 64, (
        f"SHA-256 hex digest should be 64 characters, got {len(first)}"
    )
    assert all(c in "0123456789abcdef" for c in first), (
        f"SHA-256 hex digest should only contain hex characters, got {first!r}"
    )


