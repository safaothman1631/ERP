# ─────────────────────────────────────────────────────────────────────────────
# Property 12: Empty collections are included in backup
# ─────────────────────────────────────────────────────────────────────────────

# Feature: system-health-backup, Property 12
@given(
    empty_collections=st.lists(
        st.sampled_from(BackupService.COLLECTIONS),
        min_size=0,
        max_size=len(BackupService.COLLECTIONS),
    ).map(list)  # deduplicate via set then back to list
)
@h_settings(max_examples=100)
def test_property12_empty_collections_included_in_backup(empty_collections):
    """
    **Validates: Requirements 4.8, 5.3**

    # Feature: system-health-backup, Property 12: Empty collections are included in backup

    For any subset of the 40 required collections that have zero documents,
    the backup archive SHALL still include those collections as empty arrays.
    The total document count SHALL be 0 for a fully-empty archive, satisfying
    integrity_status == "verified" when exported count == verified count == 0.
    """
    svc = _make_service()

    # Deduplicate while preserving the list (hypothesis may generate duplicates)
    unique_empty = list(dict.fromkeys(empty_collections))

    # Build an archive where the selected collections are explicitly empty
    collections: dict[str, list] = {col: [] for col in unique_empty}

    archive_payload = {
        "org_id": "test-org",
        "exported_at": "2024-01-15T02:00:00+00:00",
        "version": "1.0",
        "collections": collections,
    }

    # Serialize → compress → decompress → parse
    raw_bytes = svc._serialize_to_json(archive_payload)
    compressed = svc._compress(raw_bytes)
    decompressed = gzip.decompress(compressed)
    parsed = json.loads(decompressed)

    parsed_collections = parsed["collections"]

    # Every listed empty collection must appear in the archive as []
    for col in unique_empty:
        assert col in parsed_collections, (
            f"Empty collection '{col}' is missing from the backup archive"
        )
        assert parsed_collections[col] == [], (
            f"Collection '{col}' should be an empty list, got {parsed_collections[col]!r}"
        )

    # Total document count across all collections must be 0
    total_docs = sum(len(docs) for docs in parsed_collections.values())
    assert total_docs == 0, (
        f"Expected 0 total documents for an all-empty archive, got {total_docs}"
    )

    # Integrity condition: exported count (0) == verified count (0) → "verified"
    # Simulate the integrity check: count docs in the parsed archive
    exported_count = 0  # all collections are empty
    verified_count = sum(len(docs) for docs in parsed_collections.values())
    assert exported_count == verified_count, (
        f"Integrity check should pass (0 == 0) for empty archive, "
        f"but exported={exported_count}, verified={verified_count}"
    )


