    if mock_firebase_client:
        mock_firebase_client.get_db = MagicMock(return_value=mock_db)

    try:
        asyncio.run(svc._notify_failure(record))
    finally:
        # Restore originals
        if original_email_mod is not None:
            sys.modules["app.services.email_service"] = original_email_mod
        else:
            sys.modules.pop("app.services.email_service", None)
        if mock_firebase_client and original_get_db is not None:
            mock_firebase_client.get_db = original_get_db

    assert len(send_email_calls) == k, (
        f"Expected send_email to be called exactly {k} times for {k} admin/owner users, "
        f"got {len(send_email_calls)} calls"
    )


