@router.get("", dependencies=[Depends(require_perm("reports.read"))])
def list_scheduled_reports(user: dict = Depends(get_current_user)):
    """List all scheduled reports for the organization"""
    org_id = user.get("org_id")
    repo = ScheduledReportRepository(org_id)
    items, total = repo.list(order_by="created_at", order_dir="DESCENDING", limit=100)
    return {"items": items, "total": total}


@router.post("", dependencies=[Depends(require_perm("reports.write"))])
def create_scheduled_report(
    data: ScheduledReportCreate,
    user: dict = Depends(get_current_user)
):
    """Create a new scheduled report"""
    org_id = user.get("org_id")
    repo = ScheduledReportRepository(org_id)

    # Calculate next run time
    next_run = repo.calculate_next_run(
        data.frequency, 
        data.day_of_week, 
        data.day_of_month, 
        data.hour
    )

    report_doc = {
        "id": str(uuid.uuid4()),
        "org_id": org_id,
        "name": data.name,
        "report_type": data.report_type,
        "report_config": data.report_config,
        "frequency": data.frequency,
        "day_of_week": data.day_of_week,
        "day_of_month": data.day_of_month,
        "hour": data.hour,
        "recipients": data.recipients,
        "format": data.format,
        "active": data.active,
        "last_run_at": None,
        "next_run_at": next_run.isoformat() if next_run else None,
        "created_at": datetime.utcnow().isoformat(),
        "created_by": user.get("uid"),
    }
    repo.create(report_doc["id"], report_doc)
    return report_doc


@router.get("/{report_id}", dependencies=[Depends(require_perm("reports.read"))])
def get_scheduled_report(
    report_id: str = Path(...),
    user: dict = Depends(get_current_user)
):
    """Get a scheduled report by ID"""
    org_id = user.get("org_id")
    repo = ScheduledReportRepository(org_id)
    report = repo.get(report_id)
    if not report:
        raise HTTPException(status_code=404, detail="Report not found")
    return report


@router.put("/{report_id}", dependencies=[Depends(require_perm("reports.write"))])
def update_scheduled_report(
    data: ScheduledReportUpdate,
    report_id: str = Path(...),
    user: dict = Depends(get_current_user)
):
    """Update a scheduled report"""
    org_id = user.get("org_id")
    repo = ScheduledReportRepository(org_id)

    existing = repo.get(report_id)
    if not existing:
        raise HTTPException(status_code=404, detail="Report not found")

    update_data = {k: v for k, v in data.model_dump(exclude_unset=True).items() if v is not None}

    # Recalculate next_run if frequency/timing changed
    if any(k in update_data for k in ["frequency", "day_of_week", "day_of_month", "hour"]):
        frequency = update_data.get("frequency", existing.get("frequency"))
        day_of_week = update_data.get("day_of_week", existing.get("day_of_week"))
        day_of_month = update_data.get("day_of_month", existing.get("day_of_month"))
        hour = update_data.get("hour", existing.get("hour"))
        next_run = repo.calculate_next_run(frequency, day_of_week, day_of_month, hour)
        update_data["next_run_at"] = next_run.isoformat() if next_run else None

    repo.update(report_id, update_data)
    return {**existing, **update_data}


@router.delete("/{report_id}", dependencies=[Depends(require_perm("reports.write"))])
def delete_scheduled_report(
    report_id: str = Path(...),
    user: dict = Depends(get_current_user)
):
    """Delete a scheduled report"""
    org_id = user.get("org_id")
    repo = ScheduledReportRepository(org_id)

    existing = repo.get(report_id)
    if not existing:
        raise HTTPException(status_code=404, detail="Report not found")

    repo.delete(report_id)
    return {"message": "Report deleted"}


@router.post("/{report_id}/run-now", dependencies=[Depends(require_perm("reports.write"))])
def run_report_now(
    report_id: str = Path(...),
    user: dict = Depends(get_current_user)
):
    """Manually trigger a scheduled report"""
    org_id = user.get("org_id")
    result = _execute_scheduled_report(org_id, report_id)
    return {"message": "Report executed", **result}


@router.post("/{report_id}/toggle", dependencies=[Depends(require_perm("reports.write"))])
def toggle_report_active(
    report_id: str = Path(...),
    user: dict = Depends(get_current_user)
):
    """Toggle active status of a scheduled report"""
    org_id = user.get("org_id")
    repo = ScheduledReportRepository(org_id)

    existing = repo.get(report_id)
    if not existing:
        raise HTTPException(status_code=404, detail="Report not found")

    new_active = not existing.get("active", True)
    repo.update(report_id, {"active": new_active})

    return {"active": new_active}
