def _generate_report_html(org_id: str, report: dict) -> str:
    """Generate HTML body for a scheduled report. Pulls live aggregate data from repositories."""
    rtype = report.get("report_type", "summary")
    name = report.get("name", "Report")
    cfg = report.get("report_config") or {}
    rows: list[str] = []
    try:
        if rtype in ("sales_summary", "aging"):
            from app.firestore.invoices import InvoiceRepository
            invs, total = InvoiceRepository(org_id).list(limit=1000)
            n = len(invs)
            paid = sum(1 for i in invs if (i.get("status") or "").lower() == "paid")
            outstanding = sum(float(i.get("balance_due") or 0) for i in invs)
            grand = sum(float(i.get("total") or 0) for i in invs)
            rows = [
                f"<tr><td>Invoices</td><td>{n}</td></tr>",
                f"<tr><td>Paid</td><td>{paid}</td></tr>",
                f"<tr><td>Total Billed</td><td>{grand:,.2f}</td></tr>",
                f"<tr><td>Outstanding</td><td>{outstanding:,.2f}</td></tr>",
            ]
        elif rtype in ("pl", "profit_loss", "balance_sheet"):
            from app.firestore.journals import JournalEntryRepository
            jes, total = JournalEntryRepository(org_id).list(limit=1000)
            tot_dr = sum(float(j.get("total_debit") or 0) for j in jes)
            tot_cr = sum(float(j.get("total_credit") or 0) for j in jes)
            rows = [
                f"<tr><td>Journal Entries</td><td>{len(jes)}</td></tr>",
                f"<tr><td>Total Debit</td><td>{tot_dr:,.2f}</td></tr>",
                f"<tr><td>Total Credit</td><td>{tot_cr:,.2f}</td></tr>",
            ]
        elif rtype == "inventory_summary":
            from app.firestore.inventory import ItemRepository
            items, total = ItemRepository(org_id).list(limit=1000)
            rows = [
                f"<tr><td>Items</td><td>{len(items)}</td></tr>",
                f"<tr><td>Active</td><td>{sum(1 for i in items if i.get('is_active', True))}</td></tr>",
            ]
        else:
            rows = [f"<tr><td>Type</td><td>{rtype}</td></tr>"]
    except Exception as ex:
        rows = [f"<tr><td>Error gathering data</td><td>{ex}</td></tr>"]
    body = "".join(rows)
    return (
        f"<html><body style='font-family:Arial,sans-serif'>"
        f"<h2>{name}</h2>"
        f"<p>Report type: <b>{rtype}</b><br/>Generated at: {datetime.utcnow().isoformat()}Z</p>"
        f"<table border='1' cellpadding='6' cellspacing='0'>{body}</table>"
        f"<p style='color:#888;font-size:11px'>Auto-generated by Zoho ERP scheduled reports.</p>"
        f"</body></html>"
    )


def _execute_scheduled_report(org_id: str, report_id: str) -> dict:
    """Execute a scheduled report: generate content + email recipients + update timestamps."""
    repo = ScheduledReportRepository(org_id)
    report = repo.get(report_id)
    
    if not report:
        raise ValueError(f"Report {report_id} not found")
    
    now = datetime.utcnow()
    next_run = repo.calculate_next_run(
        report.get("frequency"),
        report.get("day_of_week"),
        report.get("day_of_month"),
        report.get("hour")
    )
    
    # Generate report HTML (pulls live data)
    html_body = _generate_report_html(org_id, report)
    subject = f"[Scheduled Report] {report.get('name', 'Report')} — {now.strftime('%Y-%m-%d')}"
    
    # Send to all recipients (best-effort; SMTP missing => skip gracefully)
    sent_count = 0
    errors: list[str] = []
    recipients = report.get("recipients") or []
    if recipients:
        try:
            from app.services.email_service import send_email
            for to in recipients:
                try:
                    send_email(
                        org_id=org_id,
                        to_email=to,
                        subject=subject,
                        body_html=html_body,
                        entity_type="scheduled_report",
                        entity_id=report_id,
                    )
                    sent_count += 1
                except Exception as ex:
                    errors.append(f"{to}: {ex}")
        except Exception as ex:
            errors.append(f"email_service unavailable: {ex}")
    
    repo.update(report_id, {
        "last_run_at": now.isoformat(),
        "next_run_at": next_run.isoformat() if next_run else None,
        "last_run_status": "ok" if not errors else ("partial" if sent_count else "failed"),
        "last_run_sent": sent_count,
        "last_run_errors": errors[:10],
    })
    
    return {
        "report_id": report_id,
        "executed_at": now.isoformat(),
        "next_run_at": next_run.isoformat() if next_run else None,
        "recipients_count": len(recipients),
        "sent_count": sent_count,
        "errors": errors,
    }


