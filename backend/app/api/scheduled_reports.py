# API endpoints for scheduled reports
from fastapi import APIRouter, Depends, HTTPException, Path
from pydantic import BaseModel, Field
from typing import Optional, Any
from datetime import datetime
from app.firestore.scheduled_reports import ScheduledReportRepository
from app.services.auth import get_current_user
from app.services.permissions import require_perm
import uuid

router = APIRouter(prefix="/api/scheduled-reports", tags=["ScheduledReports"])


class ScheduledReportCreate(BaseModel):
    name: str = Field(..., min_length=1, max_length=100)
    report_type: str = Field(..., description="sales_summary|aging|pl|balance_sheet|inventory_summary|custom")
    report_config: dict[str, Any] = Field(default_factory=dict)
    frequency: str = Field(..., description="daily|weekly|monthly")
    day_of_week: Optional[int] = Field(None, ge=0, le=6, description="0=Monday, 6=Sunday (for weekly)")
    day_of_month: Optional[int] = Field(None, ge=1, le=28, description="1-28 (for monthly)")
    hour: int = Field(9, ge=0, le=23, description="Hour of day to run (0-23)")
    recipients: list[str] = Field(default_factory=list, description="Email addresses")
    format: str = Field("pdf", description="pdf|csv|xlsx")
    active: bool = True


class ScheduledReportUpdate(BaseModel):
    name: Optional[str] = None
    report_type: Optional[str] = None
    report_config: Optional[dict[str, Any]] = None
    frequency: Optional[str] = None
    day_of_week: Optional[int] = None
    day_of_month: Optional[int] = None
    hour: Optional[int] = None
    recipients: Optional[list[str]] = None
    format: Optional[str] = None
    active: Optional[bool] = None


